/* 一键复制的完整脚本文本 */
window.scriptToText = function (topic, scenes) {
  let t = `【${topic}】爆款短剧 · 分镜脚本\n`;
  t += `【核心卖点】反转+情绪+悬念三合一，前3秒抛出最大矛盾\n`;
  t += `【角色设定】主角A（被迫隐忍/受委屈方）／主角B（强势/隐藏秘密方）／配角（线索提供者）\n`;
  t += `【场景设定】主场景×1（核心冲突发生地）＋辅场景×1（转折揭示地）\n`;
  t += `【节奏】45秒/6镜，钩子3秒内，反转点在第32秒\n\n`;
  scenes.forEach((s, i) => {
    t += `—— 第${i + 1}镜 · ${s.name}（${s.time}）——\n`;
    t += `【场景描述】${s.sub}\n`;
    t += `【镜头语言】${s.shots}\n`;
    t += `【台词/字幕】${s.lines}\n`;
    t += `【音乐建议】${s.music}\n\n`;
  });
  t += `【运营建议】封面用「情绪冲突最强」一帧；发布前2小时在评论区埋互动话题；标题带悬念关键词。`;
  return t;
};
